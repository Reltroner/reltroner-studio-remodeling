import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {renderGate,patchCountry} from '../tools/reconcile-asthortera-nccm-v65.mjs';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const ledger=JSON.parse(readFileSync(path.join(root,'data/asthortera/nccm-v6-active-cross-domain.json'),'utf8'));
const nations=[...ledger.countries_14,...ledger.countries_5];
const read=(c)=>readFileSync(path.join(root,c.source),'utf8');
test('All 19 Year 0 national profiles are creator-ratified C and deterministically reconciled to the live ledger',()=>{
 assert.equal(nations.length,19);
 assert.equal(ledger.canon_ratification.status,'C');
 for(const c of nations){
  const content=read(c),gate=renderGate(c);
  assert.equal(content.split('<!-- BEGIN NCCM_V65_FULL_PROFILE_INTEGRATION -->').length,2,'One gate: '+c.name);
  assert.ok(content.includes(gate),'Ledger-derived C gate mismatch: '+c.name);
  assert.equal(patchCountry(content,c),content,'Remodeler drift: '+c.name);
  assert.match(content,/<!-- BEGIN NCCM_V6_5_CANON_C_AUTOGENERATED -->/);
  assert.ok(gate.includes('TFR **'+c.tfr_candidate.toFixed(2)+'**'),c.name+' TFR');
  assert.ok(gate.includes('real GDP growth **'+(c.real_gdp_growth*100).toFixed(2)+'%**'),c.name+' real growth');
  assert.ok(gate.includes('USD '+Number(c.gdp_usd_annual_V6).toExponential(12)),c.name+' GDP');
  assert.ok(gate.includes('SDI **'+c.sdi.toFixed(3)+'**'),c.name+' SDI');
  if(c.ancestry_primary_pct==null)assert.match(gate,/national six-way primary ancestry: \*\*Unassigned \(not zero\)\*\*/i,c.name);
 }
});
test('All 14 old V3 national tables are labelled historical and cannot override V6.5',()=>{
 for(const c of ledger.countries_14){
  const src=read(c);
  assert.match(src,/## ARCHIVED — NCCM V3/,c.name);
  if(c.name!=='Reltronland')assert.match(src,/<!-- NCCM_V65_ARCHIVED_V3_NOT_CURRENT -->/,c.name);
 }
});
test('Five Eastern national TFRs are ratified C while unknown ancestries, age, CPI and Gini remain unassigned',()=>{
 for(const c of ledger.countries_5){
  const s=read(c);
  assert.ok(s.includes('| National total fertility rate (Year 0 C) | **'+c.tfr_candidate.toFixed(2)+'** |'),c.name);
  assert.match(renderGate(c),/Median age: \*\*Unassigned \(not zero\)\*\*/);
  assert.match(renderGate(c),/income Gini: \*\*Unassigned \(not zero\)\*\*/);
  assert.match(renderGate(c),/national six-way primary ancestry: \*\*Unassigned \(not zero\)\*\*/i);
 }
});
test('No silent pre-Model-B GNI headlines or old aggregate population split remain in key active profiles',()=>{
 const file=n=>readFileSync(path.join(root,'content/factions/'+n+'.md'),'utf8');
 assert.match(file('kalgered'),/GNI per Capita \(Year 0 NCCM V6\.5 C\).*KAL 276,949,053\/year/);
 assert.match(file('taramistry'),/Gross National Income Per Capita \(Year 0 NCCM V6\.5 C\).*TAR 225,749,246 \/ year/);
 assert.match(file('taramistry'),/Year 0 real growth is 4\.39% canon C/);
 assert.match(file('lenternow'),/GDP \(NCCM V6\.5 Year 0 C\)/);
 assert.match(file('lenternow'),/GDP\/GNI per resident \(Year 0 C\)/);
 assert.match(file('mapether'),/the 14 countries contain \*\*3,213 billion\*\*/);
 assert.match(file('mapether'),/five Eastern countries \*\*395 billion\*\*/);
 assert.match(file('scenrepolia'),/national TFR \*\*1\.66 canon C\*\*/);
});
